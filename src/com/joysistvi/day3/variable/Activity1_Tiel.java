package com.joysistvi.day3.variable;

public class Activity1_Tiel {
    public static void main(String[] args) { // main method
        // Boolean type
        boolean isBoolean = true;

        // Integer types
        byte numByte = 50;
        short numShort = 500;
        int numInt = 50_000;
        long numLong = 1_000_000_000L;

        // Floating-point types
        float numFloat = 5.75f;
        double numDouble = 19.99;

        // Character type
        char letterChar = 'A';

        // Reference type
        String textString = "Hello, Java!";

        // Display values
        System.out.println("Boolean: " + isBoolean);
        System.out.println("Byte: " + numByte);
        System.out.println("Short: " + numShort);
        System.out.println("Int: " + numInt);
        System.out.println("Long: " + numLong);
        System.out.println("Float: " + numFloat);
        System.out.println("Double: " + numDouble);
        System.out.println("Char: " + letterChar);
        System.out.println("String: " + textString);
    }
}
